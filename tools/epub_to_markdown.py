# Footnote loader
# ---------------------------------------------------------------------------

def load_footnote_lookup(html: str, fmt: str = "by_a_id",
                         italic_classes: set[str] | None = None,
                         bold_classes: set[str] | None = None) -> dict[str, str]:
    """Parse a footnote-pool file into {anchor_id -> markdown body}.

    Three formats are supported:

    * `by_a_id` (default, Study Quran / Davies pattern):
        <p class="footnote"><a id="bX_fnN" href="...">N.</a> body...</p>
      The id lives on the first <a> *inside* the paragraph.
    * `by_p_id` (Smith *El enigma cuántico* pattern):
        <div class="nota"><p id="ntN"><sup>[N]</sup> body... <a href="ref">&lt;&lt;</a></p></div>
      The id lives on the `<p>` itself; the body has a leading <sup>[N]</sup>
      and a trailing back-link `<a>` that we strip.
    * `by_a_id_any` (Calibre/Kindle pattern, e.g. Picatrix Liber Atratus):
        <p class="calibre_2">[<a id="filepos…" href="…">N</a>] body...</p>
      Same idea as `by_a_id` but the paragraph carries an arbitrary class, so
      we accept ANY <p> whose first <a> has an id, and strip the surrounding
      brackets of the leading `[N]` marker.
    * `by_a_id_split` (Calibre/Kindle *flat* pool, e.g. Warnock & Greer's
      *Astral High Magic*):
        <p class="calibre_14">
          <a id="filepos…"></a>1. body… [<a href="…">return</a>]<br/><br/>
          <a id="filepos…"></a>2. body… [<a href="…">return</a>]<br/><br/>
        </p>
      ALL the notes live inside ONE paragraph, separated by <br/>, so there is
      no per-note element to iterate over: the note boundary is the empty
      `<a id=…></a>` anchor itself, and we split the raw HTML on it.
    """
    soup = BeautifulSoup(html, "html.parser")
    out: dict[str, str] = {}

    if fmt == "by_a_id_split":
        parts = re.split(r'<a\s+id="([^"]+)"\s*>\s*</a>', html)
        # parts = [preamble, id1, body1, id2, body2, …]
        for anchor_id, chunk in zip(parts[1::2], parts[2::2]):
            frag = BeautifulSoup(chunk, "html.parser")
            # Drop the trailing back-link ("[return]") and its brackets.
            for a in list(frag.find_all("a")):
                if a.get_text(strip=True).lower() in ("return", "back", "↩", "↑"):
                    a.decompose()
            conv = Converter(footnote_lookup={},
                             italic_classes=italic_classes,
                             bold_classes=bold_classes)
            text = "".join(conv._inline(c) for c in frag.children)
            text = re.sub(r"\[\s*\]\s*$", "", text.strip())
            # Leading note number left behind by the extracted anchor ("12. ").
            text = re.sub(r"^\s*\d+\.\s*", "", text)
            text = re.sub(r"\s+", " ", text).strip()
            if text:
                out[anchor_id] = text
        return out

    if fmt == "by_p_id":
        # Find all paragraphs with an id (they may be inside <div class="nota">).
        for p in soup.find_all("p"):
            if not isinstance(p, Tag):
                continue
            anchor_id = _attr(p, "id")
            if not anchor_id:
                continue
            # Drop the back-link <a> — trailing (`<<`, `↩`) or LEADING. In the
            # Inner Traditions layout (Purdue's Agrippa) the note opens with its
            # own number as the link back to the call:
            #   <p id="nt36"><a href="…#nr36"><b>1</b></a>. body…
            # so the marker to strip is an <a> whose text is just a number.
            anchors = [a for a in p.find_all("a") if isinstance(a, Tag)]
            for i, a in enumerate(anchors):
                href = _attr(a, "href")
                if "#" not in href:
                    continue
                txt = a.get_text(strip=True)
                if txt in ("<<", "‹‹", "↩", "↑"):
                    a.extract()
                elif i == 0 and re.fullmatch(r"\[?\d+\]?\.?", txt):
                    a.extract()
            # Drop the leading <sup>[N]</sup>
            sup = p.find("sup")
            if isinstance(sup, Tag):
                inner = sup.get_text(strip=True)
                # Match patterns like "[1]" or "1"
                if re.fullmatch(r"\[?\d+\]?", inner):
                    sup.extract()
            conv = Converter(footnote_lookup={},
                             italic_classes=italic_classes,
                             bold_classes=bold_classes)
            text = "".join(conv._inline(c) for c in p.children)
            # Marcador que quede tras extraer el ancla: "N.", "[N]" o el punto
            # SUELTO que seguía al número enlazado (Inner Traditions).
            text = re.sub(r"^\s*\[?\d+\]?\.?\s*", "", text)
            text = re.sub(r"^\s*\.\s+", "", text)
            text = re.sub(r"\s+", " ", text).strip()
            if text:
                out[anchor_id] = text
        return out

    # by_a_id (default) and by_a_id_any: the id lives on the first <a> inside
    # the paragraph. They differ only in which paragraphs are eligible.
    if fmt == "by_a_id_any":
        candidates = [p for p in soup.find_all("p") if isinstance(p, Tag)]
    else:
        candidates = [p for p in soup.find_all("p", class_="footnote")
                      if isinstance(p, Tag)]
    for p in candidates:
        a = p.find("a")
        if not isinstance(a, Tag):
            continue
        anchor_id = _attr(a, "id")
        if not anchor_id:
            continue
        a.extract()
        conv = Converter(footnote_lookup={},
                             italic_classes=italic_classes,
                             bold_classes=bold_classes)
        text = "".join(conv._inline(c) for c in p.children)
        # Leading marker left behind by the extracted <a>: "N." or the
        # brackets of "[N]" (by_a_id_any).
        text = re.sub(r"^\s*\d+\.\s*", "", text)
        text = re.sub(r"^\s*\[\s*\]\s*", "", text)
        text = re.sub(r"\s+", " ", text).strip()
        if text:
            out[anchor_id] = text
    return out


# ---------------------------------------------------------------------------
# Post-processing
# ---------------------------------------------------------------------------

def tidy_blockquotes(lines: list[str]) -> str | list[str]:
    """Quita los `>` VACÍOS sobrantes dentro de una cita.

    Un `<blockquote>` de portadilla mezcla párrafos e imágenes, y como la imagen
    se emite rodeada de renglones en blanco, la cita sale con rachas de `>`
    huérfanos (`>`, `>`, `> texto`, `>`, `>`). Un solo `>` entre dos párrafos es
    el separador correcto; dos seguidos son ruido, y al principio o al final de
    la cita sobran siempre.
    """
    out: list[str] = []
    for ln in lines:
        bare = ln.strip() == ">"
        if bare:
            # Nunca abrir la cita con un `>` vacío, ni repetirlo.
            if not out or out[-1].strip() == ">" or not out[-1].lstrip().startswith(">"):
                continue
        out.append(ln)
    # Ni cerrarla con uno.
    while out and out[-1].strip() == ">":
        out.pop()
    return out


def tidy_markdown(lines: list[str]) -> str:
    """Collapse multiple blank lines, strip trailing whitespace, normalize."""
    lines = tidy_blockquotes(lines)
    out: list[str] = []
    prev_blank = False
    for ln in lines:
        rstripped = ln.rstrip()
        is_blank = rstripped == ""
        if is_blank and prev_blank:
            continue
        out.append(rstripped)
        prev_blank = is_blank
    # Strip leading/trailing blank lines
    while out and out[0].strip() == "":
        out.pop(0)
    while out and out[-1].strip() == "":
        out.pop()
    return "\n".join(out) + "\n"


