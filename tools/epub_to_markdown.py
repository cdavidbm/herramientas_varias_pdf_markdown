# ---------------------------------------------------------------------------
# Utility
# ---------------------------------------------------------------------------

def _classes(node: Tag) -> list[str]:
    raw = node.get("class")
    if raw is None:
        return []
    if isinstance(raw, str):
        return raw.split()
    return [str(c) for c in raw]


def _attr(node: Tag, name: str) -> str:
    raw = node.get(name)
    if raw is None:
        return ""
    if isinstance(raw, str):
        return raw
    if isinstance(raw, (list, tuple)):
        return " ".join(str(x) for x in raw)
    return str(raw)


# ---------------------------------------------------------------------------
# XHTML → Markdown conversion
# ---------------------------------------------------------------------------

SKIP_CLASSES = {"image"}  # decorative images inline
SKIP_TAGS = {"style", "script", "meta", "link", "head", "title"}

# Local (same-file) footnote anchors: a ref `<a href="#footnote-015">1</a>` whose
# body lives in the same document as `<… id="footnote-015">…</…>`. This is the
# default Calibre / InDesign pattern (`_idFootnote`), distinct from the pooled
# `Footnote.xhtml#anchor` pattern handled via footnote_markers.
NOTE_ID_RE = re.compile(r"(footnote|endnote|fn|note|nota)[-_]?\d", re.IGNORECASE)
NOTE_CLASS_RE = re.compile(r"(footnote|endnote|nota|note)", re.IGNORECASE)


def styles_from_css(css: str) -> tuple[set[str], set[str]]:
    """Return ({classes that are italic}, {classes that are bold}) from a stylesheet.

    Calibre/Kindle EPUBs almost never use <i>/<em>: the emphasis lives in a
    class (`<span class="italic">`, or an opaque `<span class="calibre12">`
    whose rule is `font-style: italic`). Reading it from the book's OWN CSS
    keeps this general instead of hardcoding class names per book.
    """
    italic: set[str] = set()
    bold: set[str] = set()
    # Strip comments, then walk `selector { body }` rules.
    css = re.sub(r"/\*.*?\*/", " ", css, flags=re.S)
    for sel, body in re.findall(r"([^{}]+)\{([^{}]*)\}", css):
        is_it = re.search(r"font-style\s*:\s*(italic|oblique)", body, re.I)
        # `font-weight: bold` or a numeric weight of 600+.
        is_bd = (re.search(r"font-weight\s*:\s*bold", body, re.I)
                 or re.search(r"font-weight\s*:\s*([6-9]\d\d)", body))
        if not (is_it or is_bd):
            continue
        for part in sel.split(","):
            # Only take plain class selectors (`.italic`, `p.foo`): a compound
            # or descendant selector would over-apply.
            m = re.fullmatch(r"\s*[a-zA-Z0-9]*\.([A-Za-z0-9_-]+)\s*", part)
            if not m:
                continue
            if is_it:
                italic.add(m.group(1))
            if is_bd:
                bold.add(m.group(1))
    return italic, bold


class Converter:
    """Converts a soup body into markdown lines.

    Footnote bodies are loaded once from the shared Footnote file and resolved
    on demand when a `<sup><a href="...Footnote.xhtml#bX_fnN">` ref is encountered.
    Numbering within each output section is reset at convert_file() boundaries
    and assembled in read order.
    """

    def __init__(self, footnote_lookup: dict[str, str] | None = None,
                 footnote_file_marker: str | list[str] = "Footnote.xhtml",
                 section_title: str = "",
                 italic_classes: set[str] | None = None,
                 bold_classes: set[str] | None = None,
                 heading_paragraphs: dict[str, int] | None = None,
                 image_dir: str = "",
                 image_skip: set[str] | None = None,
                 image_root: Path | None = None,
                 inline_img_px: int = 60):
        self.footnote_lookup = footnote_lookup or {}
        # Emphasis carried by CSS CLASS instead of <i>/<em> (Calibre and most
        # Kindle exports do this: <span class="italic"> or <span class="calibre12">
        # whose rule is `font-style: italic`). Derived from the book's own
        # stylesheets by styles_from_css(), so this is not a hardcoded guess.
        self.italic_classes = italic_classes or set()
        self.bold_classes = bold_classes or set()
        # {css_class: heading level} for books whose subheadings are bold <p>s
        # rather than <hN> (plan key `heading_paragraphs`).
        self.heading_paragraphs = heading_paragraphs or {}
        # Relative dir used in the markdown link, e.g. "imagenes". Empty = drop
        # images (previous behaviour). `image_skip` holds basenames to ignore
        # (the cover, decorative rules...).
        self.image_dir = image_dir
        self.image_skip = image_skip or set()
        self.used_images: set[str] = set()
        # Altura (px) por debajo de la cual una imagen se considera un glifo
        # inline y no una lámina. Necesita la raíz del EPUB para medirla.
        self.inline_img_px = inline_img_px
        self.image_root = image_root
        self._img_cache: dict[str, int] = {}
        # Normalised section title, used to suppress an in-document heading that
        # merely repeats the plan-provided H1 (a very common EPUB duplication,
        # independent of the book's CSS classes).
        self.section_title_norm = re.sub(r"\s+", " ", section_title).strip().lower()
        # Local (same-file) footnote support: bare ids of note bodies found in
        # the file currently being converted, and that file's name (used to
        # namespace ids so two files in one section can't collide).
        self.local_note_ids: set[str] = set()
        self.current_file = ""
        # Nº de bloques emitidos en el archivo actual: lo usa la supresión del
        # título partido, que solo debe actuar en la cabecera del documento.
        self._block_index = 0
        self.used_footnotes: list[tuple[int, str]] = []
        self.footnote_counter = 0
        self.footnote_seen: dict[str, int] = {}
        # Substring(s) used to detect that a <sup><a href> points at the
        # footnote pool. Can be a single string or a list (any-match).
        # Examples:
        #   "Footnote.xhtml" — Study Quran
        #   "appendix001.html" — Davies *God and the New Physics*
        #   ["notas001.xhtml", "notas002.xhtml", ...] — Smith *El enigma
        #     cuántico* (one notes file per chapter)
        if isinstance(footnote_file_marker, str):
            raw_markers = [footnote_file_marker]
        else:
            raw_markers = list(footnote_file_marker)
        # Also match by basename: a plan may carry the pool as "text/Foo.xhtml"
        # while the in-document hrefs reference just "Foo.xhtml#anchor".
        markers: list[str] = []
        for m in raw_markers:
            if not m:
                continue
            if m not in markers:
                markers.append(m)
            base = m.rsplit("/", 1)[-1]
            if base and base not in markers:
                markers.append(base)
        self.footnote_markers: list[str] = markers

    # ---- footnote bookkeeping ----------------------------------------------

    def _resolve_footnote(self, anchor_id: str) -> int:
        """Return the 1-based local footnote number for a given `Footnote.xhtml#bX_fnN` anchor."""
        if anchor_id in self.footnote_seen:
            return self.footnote_seen[anchor_id]
        self.footnote_counter += 1
        num = self.footnote_counter
        self.footnote_seen[anchor_id] = num
        body = self.footnote_lookup.get(anchor_id, f"_[missing footnote: {anchor_id}]_")
        self.used_footnotes.append((num, body))
        return num

    def _img_height(self, src: str) -> int:
        """Alto en px del JPEG/PNG, leído de la cabecera (0 si no se puede)."""
        if src in self._img_cache:
            return self._img_cache[src]
        h = 0
        if self.image_root:
            hits = [self.image_root / src]
            hits += list(self.image_root.rglob(src.rsplit("/", 1)[-1]))
            for cand in hits:
                if not cand.is_file():
                    continue
                b = cand.read_bytes()
                try:
                    if b[:2] == b"\xff\xd8":                      # JPEG
                        i = 2
                        while i < len(b) - 9 and b[i] == 0xFF:
                            if b[i + 1] in (0xC0, 0xC1, 0xC2):
                                h = int.from_bytes(b[i + 5:i + 7], "big"); break
                            i += 2 + int.from_bytes(b[i + 2:i + 4], "big")
                    elif b[1:4] == b"PNG":
                        h = int.from_bytes(b[20:24], "big")
                except Exception:
                    h = 0
                break
        self._img_cache[src] = h
        return h

    # ---- inline -------------------------------------------------------------

    def _inline(self, node) -> str:
        if isinstance(node, NavigableString):
            # A newline in the SOURCE is just whitespace in HTML, but keeping it
            # verbatim breaks the line mid-sentence — and when it lands right
            # before a <sup> note ref, the call ends up alone on its own line,
            # which pandoc then renders as a separate paragraph. Collapse it to
            # a space; a real line break only comes from <br>, handled below.
            return re.sub(r"[ \t]*\n[ \t\r\n]*", " ", str(node))
        if not isinstance(node, Tag):
            return ""
        if node.name in SKIP_TAGS:
            return ""

        classes = _classes(node)
        # Drop decorative pagebreaks and images
        if _attr(node, "epub:type") == "pagebreak":
            return ""
        if node.name == "img":
            # Images are CONTENT in illustrated books (charts, talismans,
            # diagrams) and dropping them is a silent loss. With --images they
            # are copied out and linked; without it we keep the old behaviour.
            src = _attr(node, "src")
            if not self.image_dir or not src:
                return ""
            name = src.rsplit("/", 1)[-1]
            if name in self.image_skip:
                return ""
            self.used_images.add(src)
            alt = _attr(node, "alt").strip()
            # Una imagen DIMINUTA es un glifo a media frase (un signo zodiacal, una
            # palabra en otro alfabeto), no una lámina. Emitirla como BLOQUE parte
            # la frase en tantos trozos como glifos —37 en el cap. 52 de Agripa— y
            # el párrafo deja de leerse, en el markdown y en el PDF. Va en LÍNEA.
            if self._img_height(src) and self._img_height(src) <= self.inline_img_px:
                return f"![{alt}]({self.image_dir}/{name})"
            return f"\n\n![{alt}]({self.image_dir}/{name})\n\n"
        if "image" in classes:
            return ""
        # Special HarperCollins font spans just carry their content
        if set(classes) & {"HCSQ", "HCSQIt", "dropcap", "hide", "right_1"}:
            return "".join(self._inline(c) for c in node.children)
        # Verse number marker (`<span class="red1">42</span>`)
        if "red1" in classes:
            inner = "".join(self._inline(c) for c in node.children).strip()
            return f"**{inner}** " if inner else ""
        # Decorative red "verse start" glyph (fancy cap letter)
        if "redr" in classes:
            return "¶"
        if "red" in classes:
            return "".join(self._inline(c) for c in node.children)

        # Footnote reference: <sup><a href="...{marker}#anchor">N</a></sup>
        if node.name == "sup":
            # OJO: el <sup> puede llevar VARIOS <a> — el primero suele ser el
            # ancla VACÍA de destino (`<a id="nr36"></a>`) y el segundo el enlace
            # real al pool. Quedarse con `find("a")` dejaba la llamada sin
            # resolver y el genérico de abajo emitía un `^` suelto delante del
            # marcador: `superior,^[^1]`. Hay que buscar el primero CON href útil.
            for a in node.find_all("a"):
                if not isinstance(a, Tag):
                    continue
                href = _attr(a, "href")
                if any(m and m in href for m in self.footnote_markers):
                    anchor_id = href.split("#", 1)[1] if "#" in href else href
                    num = self._resolve_footnote(anchor_id)
                    return f"[^{num}]"
            # generic sup (e.g. mathematical exponents, "u", "un") → keep raw
            inner = "".join(self._inline(c) for c in node.children).strip()
            return f"^{inner}" if inner else ""

        # Las marcas van FUERA del espacio: `in<em> Dionysii</em>` daría
        # `in* Dionysii*`, que pandoc imprime con los asteriscos literales.
        if node.name in ("i", "em", "b", "strong"):
            inner = "".join(self._inline(c) for c in node.children)
            if not inner.strip():
                return inner
            mark = "*" if node.name in ("i", "em") else "**"
            lead = inner[:len(inner) - len(inner.lstrip())]
            trail = inner[len(inner.rstrip()):]
            return f"{lead}{mark}{inner.strip()}{mark}{trail}"

        # Emphasis carried by CSS class (Calibre/Kindle). Keep the marks OUTSIDE
        # the surrounding whitespace: `*foo *bar` renders literally in pandoc.
        cls_italic = any(c in self.italic_classes for c in classes)
        cls_bold = any(c in self.bold_classes for c in classes)
        if (cls_italic or cls_bold) and node.name in ("span", "i", "em", "b",
                                                      "strong", "font"):
            inner = "".join(self._inline(c) for c in node.children)
            if not inner.strip():
                return inner
            lead = inner[:len(inner) - len(inner.lstrip())]
            trail = inner[len(inner.rstrip()):]
            core = inner.strip()
            if cls_bold:
                core = f"**{core}**"
            if cls_italic:
                core = f"*{core}*"
            return f"{lead}{core}{trail}"
        if node.name == "br":
            return "\n"
        if node.name == "a":
            # Footnote reference where the <a> is the OUTER element wrapping a <sup>
            # (e.g. Davies's *God and the New Physics*:
            #   <a class="footnoteref" href=".../appendix001.html#ch2fn_1"><sup>1</sup></a>)
            # Also covers Smith's per-chapter notas files (multi-marker).
            href = _attr(node, "href")
            if any(m and m in href for m in self.footnote_markers):
                anchor_id = href.split("#", 1)[1] if "#" in href else href
                num = self._resolve_footnote(anchor_id)
                return f"[^{num}]"
            # Local (same-file) footnote ref: href="#footnote-015" whose body was
            # indexed in this file by _index_local_footnotes().
            if href.startswith("#"):
                target = href[1:]
                if target in self.local_note_ids:
                    num = self._resolve_footnote(f"{self.current_file}::{target}")
                    return f"[^{num}]"
            # Internal anchor: drop link, keep text
            return "".join(self._inline(c) for c in node.children)

        # Any other inline element — just descend
        return "".join(self._inline(c) for c in node.children)

    # ---- block --------------------------------------------------------------

    def _block(self, node) -> list[str]:
        if isinstance(node, NavigableString):
            text = str(node).strip()
            return [text] if text else []
        if not isinstance(node, Tag):
            return []
        if node.name in SKIP_TAGS:
            return []

        classes = _classes(node)

        # Skip decorative image wrappers
        if "image" in classes:
            return []

        name = node.name.lower()

        # Divs and sections: descend
        if name in ("section", "div", "body"):
            lines: list[str] = []
            if "quote" in classes:
                # Introductory quote/abstract → render as blockquote paragraph
                inner_blocks = []
                for child in node.children:
                    inner_blocks.extend(self._block(child))
                # prefix every non-empty line with "> "
                for block in inner_blocks:
                    if block.strip() == "":
                        lines.append("")
                    else:
                        for ln in block.splitlines():
                            lines.append(f"> {ln}" if ln.strip() else ">")
                    lines.append("")
                return lines
            for child in node.children:
                lines.extend(self._block(child))
            return lines

        # Headings
        if name in ("h1", "h2", "h3", "h4", "h5", "h6"):
            # Suppress title/subtitle headings that duplicate our plan-provided H1.
            # Study Quran uses h2/h2a/.../h2bm1; Davies's *God and the New Physics*
            # uses calibre7 and tocHead. Add classes here as new books surface.
            SKIP_HEADER_CLASSES = {"h2", "h2a", "h2b", "h2f", "h2bm", "h2bm1",
                                   "calibre7", "tocHead"}
            if set(classes) & SKIP_HEADER_CLASSES:
                return []
            text = self._inline(node).strip()
            text = re.sub(r"\s+", " ", text)
            if not text:
                return []
            # Suppress a heading that merely repeats the plan-provided section
            # title (generic de-duplication, no per-book class needed).
            if self.section_title_norm and text.lower() == self.section_title_norm:
                return []
            level_map = {"h1": 1, "h2": 2, "h3": 3, "h4": 4, "h5": 5, "h6": 6}
            hashes = "#" * level_map[name]
            return ["", f"{hashes} {text}", ""]

        if name == "p":
            if node.get_text(strip=True):
                self._block_index += 1
            # Star separators
            if "star" in classes or node.get_text().strip() in ("***", "* * *"):
                return ["", "---", ""]
            # A paragraph whose WHOLE text is the section title is the book's own
            # chapter heading, styled as a bold <p> instead of an <h1> (the norm
            # in Calibre/Kindle exports). Suppress it: the plan already emits the
            # H1, and leaving it prints the title twice.
            if self.section_title_norm and self._block_index <= 5:
                # Guarda de POSICIÓN: el encabezado duplicado va siempre en la
                # cabecera del documento. Sin ella, un párrafo del cuerpo que
                # coincida con el título se borraría en silencio a mitad del
                # capítulo — y eso es pérdida de texto, no deduplicación.
                ptext = re.sub(r"\s+", " ", node.get_text()).strip().lower()
                if ptext == self.section_title_norm:
                    return []
                # El título del capítulo suele venir PARTIDO en dos párrafos
                # («Chapter 1» + «How magicians collect…», clases chn/cht en la
                # edición Purdue de Agripa) y el plan los une en un solo H1: cada
                # trozo por su cuenta es entonces una repetición. Se suprime solo
                # si el párrafo cae al PRINCIPIO del archivo y su texto es un
                # fragmento real del título, para no tocar prosa que casualmente
                # repita palabras del título más adelante.
                if (self._block_index < 3 and len(ptext) > 3
                        and ptext.rstrip(".") in self.section_title_norm):
                    return []
            # Book-specific subheadings styled as a bold <p> (plan key
            # `heading_paragraphs`: {css_class: level}). The class may sit on the
            # <p> or on a descendant <span>; Calibre nests them either way.
            if self.heading_paragraphs:
                seen = set(classes)
                for sp in node.find_all(("span", "div")):
                    seen.update(_classes(sp))
                for cls, level in self.heading_paragraphs.items():
                    if cls in seen:
                        text = re.sub(r"\s+", " ", self._inline(node)).strip()
                        # Drop the BOLD marks: a heading is already emphatic, and
                        # `## **X**` renders the asterisks in the TOC. A heading
                        # built from two adjacent bold spans ("Version I:" +
                        # "Part Three…") leaves `**` mid-string too, so remove
                        # them all — but keep single-`*` italics, which are
                        # meaningful in a title (work names, transliterations).
                        text = text.replace("**", "")
                        text = re.sub(r"\s+", " ", text).strip()
                        if not text:
                            return []
                        return ["", f"{'#' * level} {text}", ""]
            # Footnote paragraphs (in essays) → handled by caller via footnote file,
            # but if we encounter them inline here, emit as footnote body.
            if "footnote" in classes:
                return []
            if "h3l" in classes or "h3" in classes:
                # Verse quotations inside commentary → blockquote
                text = self._inline(node).strip()
                if not text:
                    return []
                return ["", f"> {text}", ""]
            text = self._inline(node)
            text = re.sub(r"[ \t]+", " ", text)
            text = text.strip()
            return ["", text, ""] if text else []

        if name == "h3":
            text = self._inline(node).strip()
            return ["", f"### {text}", ""] if text else []

        if name == "blockquote":
            inner = []
            for child in node.children:
                inner.extend(self._block(child))
            out = [""]
            for ln in "\n".join(inner).splitlines():
                out.append(f"> {ln}" if ln.strip() else ">")
            out.append("")
            return out

        if name == "ul":
            out = [""]
            for li in node.find_all("li", recursive=False):
                out.append(f"- {self._inline(li).strip()}")
            out.append("")
            return out

        if name == "ol":
            out = [""]
            for i, li in enumerate(node.find_all("li", recursive=False), 1):
                out.append(f"{i}. {self._inline(li).strip()}")
            out.append("")
            return out

        if name == "table":
            # Very light-weight table rendering
            rows = []
            for tr in node.find_all("tr"):
                cells = [self._inline(td).strip() for td in tr.find_all(["td", "th"])]
                rows.append("| " + " | ".join(cells) + " |")
            if rows:
                sep = "| " + " | ".join("---" for _ in rows[0].split("|")[1:-1]) + " |"
                rows.insert(1, sep)
                return ["", *rows, ""]
            return []

        # Fallback — descend
        lines = []
        for child in node.children:
            lines.extend(self._block(child))
        return lines

    # ---- public --------------------------------------------------------------

    def _local_note_body(self, el: Tag) -> str:
        """Extract a same-file footnote body, stripping its leading back-link
        and number marker."""
        target = el.find("p") or el
        if not isinstance(target, Tag):
            return ""
        # Drop return/back-link anchors (e.g. href="#footnote-015-backlink").
        for a in list(target.find_all("a")):
            if "backlink" in _attr(a, "href").lower():
                a.extract()
        text = "".join(self._inline(c) for c in target.children)
        text = re.sub(r"^\s*\[?\d+[.)\]]?\s*", "", text)   # leading "1 " / "1." / "[1]"
        return re.sub(r"\s+", " ", text).strip()

    def _index_local_footnotes(self, soup: BeautifulSoup) -> None:
        """Find note bodies referenced by same-file `href="#id"` anchors, fold
        their text into the footnote lookup, and remove them from the flow so
        they are not rendered inline."""
        targets = {
            _attr(a, "href")[1:]
            for a in soup.find_all("a")
            if _attr(a, "href").startswith("#")
        }
        for tid in targets:
            if not tid:
                continue
            el = soup.find(id=tid)
            if not isinstance(el, Tag):
                continue
            cls = " ".join(_classes(el))
            if not (NOTE_ID_RE.search(tid) or NOTE_CLASS_RE.search(cls)):
                continue  # ordinary cross-reference anchor, not a note
            key = f"{self.current_file}::{tid}"
            if key in self.footnote_lookup:
                continue
            body = self._local_note_body(el)
            if not body:
                continue
            self.footnote_lookup[key] = body
            self.local_note_ids.add(tid)
            el.decompose()

    def convert_file(self, html: str, filename: str = "") -> list[str]:
        soup = BeautifulSoup(html, "html.parser")
        self.current_file = filename
        self._block_index = 0
        self._index_local_footnotes(soup)
        body = soup.body or soup
        lines = self._block(body)
        return lines


